// درج / به‌روزرسانی
// ------------------------------------------------------------------
$upd = $db->prepare("UPDATE kb_entities
    SET description = COALESCE(?, description),
        properties  = COALESCE(?, properties),
        updated_at  = NOW()
    WHERE code = ?");

foreach ($data as $code => $row) {
    $desc = $row['description'];
    $props = $row['properties'];
    $json = json_encode($props, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    $upd->execute([$desc, $json, $code]);
    echo "updated: $code (desc=" . mb_strlen($desc) . " chars, props=" . strlen($json) . " bytes)\n";
}

echo "done\n";
